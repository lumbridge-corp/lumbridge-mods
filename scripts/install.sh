#!/usr/bin/env bash
# Installs this repo's mods, layouts and key bindings into a lumbridge-app home by
# COPYING them (lumbridge-app does not hot-reload through symlinks).
#   scripts/install.sh                          every mod + layouts + keys, here
#   scripts/install.sh lumbridge-mail             just that mod, here
#   scripts/install.sh --host laptop            everything, on another screen (ssh alias)
#   scripts/install.sh --host laptop lumbridge-favorites
# Only lumbridge-* mods and our own layouts are written; shipped files are never
# touched; keys.json is merged (scripts/merge-config.py), never replaced.
# A private/ folder, when there is one (it is not part of the public tree), adds to that:
# its layouts replace ours of the same name, its config/ is merged after ours, and its
# lumbridge-mods.json (the mods' settings, see lib/kit.js) is copied into the home.
# A lock keeps parallel agents from installing at once (here; --host is serial by hand).
# Open popups keep their old code until reopened; docked panels reload.
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)

host=""
appdir=lumbridge-app; cli=lumbridge-app
if [ "${1:-}" = "--host" ]; then host=${2:?--host needs an ssh alias}; shift 2; fi

"$root/scripts/check.sh" "$@" || { echo "install: check failed, nothing installed" >&2; exit 1; }

if [ $# -gt 0 ]; then names=("$@"); else names=(); for d in "$root"/mods/*/; do names+=("$(basename "$d")"); done; fi
layouts=()
if [ $# -eq 0 ]; then
  for f in "$root"/layouts/*.json "$root"/private/layouts/*.json; do
    [ -e "$f" ] || continue
    case $(basename "$f") in main.json|terminals.json|win98.json) echo "skip layout $(basename "$f") (shipped name)";; *) layouts+=("$f");; esac
  done
fi
# Generated by lumbridge-app itself; never ship them.
excludes=(--exclude '.*' --exclude 'gpui-kit.d.ts' --exclude 'lumbridge.d.ts' --exclude 'jsconfig.json')

if [ -z "$host" ]; then
  home=${LUMBRIDGE_APP_HOME:-$HOME/.config/$appdir}
  [ -d "$home/mods" ] || { echo "no lumbridge-app home at $home" >&2; exit 1; }
  exec 9>"$home/.lumbridge-install.lock"
  flock -w 30 9 || { echo "install: another install holds the lock" >&2; exit 1; }
  for n in "${names[@]}"; do
    case $n in lumbridge-*) ;; *) echo "skip $n (not lumbridge-*)"; continue;; esac
    rsync -a --delete "${excludes[@]}" "$root/mods/$n/" "$home/mods/$n/"
    echo "installed mod $n"
  done
  for f in "${layouts[@]}"; do
    n=$(basename "$f"); cp "$f" "$home/layouts/$n.tmp" && mv -f "$home/layouts/$n.tmp" "$home/layouts/$n"
    echo "installed layout ${n%.json}"
  done
  if [ $# -eq 0 ]; then
    LUMBRIDGE_APP_HOME=$home "$root/scripts/merge-config.py"
    if [ -f "$root/private/lumbridge-mods.json" ]; then cp "$root/private/lumbridge-mods.json" "$home/lumbridge-mods.json"; echo "installed lumbridge-mods.json"; fi
  fi
  status() { LUMBRIDGE_APP_HOME=$home $cli status; }
else
  # Another screen (e.g. a Mac: openrsync + /usr/bin/python3; lumbridge-app in ~/.local/bin).
  rhome=.config/$appdir
  ssh "$host" "test -d $rhome/mods" || { echo "no lumbridge-app home on $host (open Lumbridge there once)" >&2; exit 1; }
  for n in "${names[@]}"; do
    case $n in lumbridge-*) ;; *) echo "skip $n (not lumbridge-*)"; continue;; esac
    rsync -a --delete "${excludes[@]}" "$root/mods/$n/" "$host:$rhome/mods/$n/"
    echo "installed mod $n on $host"
  done
  for f in "${layouts[@]}"; do
    n=$(basename "$f"); rsync -a "$f" "$host:$rhome/layouts/$n"
    echo "installed layout ${n%.json} on $host"
  done
  if [ $# -eq 0 ]; then
    ssh "$host" "rm -rf $rhome/.lumbridge/private && mkdir -p $rhome/.lumbridge/config $rhome/.lumbridge/scripts"
    for c in "$root"/config/*.json; do rsync -a "$c" "$host:$rhome/.lumbridge/config/$(basename "$c")"; done
    if [ -d "$root/private/config" ]; then
      ssh "$host" "mkdir -p $rhome/.lumbridge/private/config"
      for c in "$root"/private/config/*.json; do rsync -a "$c" "$host:$rhome/.lumbridge/private/config/$(basename "$c")"; done
    fi
    if [ -f "$root/private/lumbridge-mods.json" ]; then rsync -a "$root/private/lumbridge-mods.json" "$host:$rhome/lumbridge-mods.json"; fi
    rsync -a "$root/scripts/merge-config.py" "$host:$rhome/.lumbridge/scripts/merge-config.py"
    ssh "$host" "LUMBRIDGE_APP_HOME=\$HOME/$rhome /usr/bin/python3 $rhome/.lumbridge/scripts/merge-config.py"
  fi
  status() { ssh "$host" "LUMBRIDGE_APP_HOME=\$HOME/$rhome ~/.local/bin/$cli status"; }
fi

sleep 1
if out=$(status 2>/dev/null); then
  printf '%s' "$out" | python3 -c 'import json,sys; d=json.load(sys.stdin); e=d.get("errors") or []; print("window errors:", e if e else "none"); sys.exit(1 if e else 0)'
else
  echo "window: not running (installed files apply when Lumbridge opens)"
fi
